import { useState } from 'react';
import { useAppStore } from '../store/appStore';
import { Wallet, CreditCard, Landmark, Download, ShieldCheck, Info } from 'lucide-react';
import AppLayout from '../components/AppLayout';
import Modal from '../components/Modal';
import { PaymentStatusBadge } from '../components/Badge';
import { useToast } from '../components/Toast';
import { formatINR, formatDate, monthLabel, currentMonth } from '../utils/format';
import type { Payment, PaymentMethod } from '../types';

function downloadReceipt(payment: Payment, tenantName: string, pgName: string, roomNumber: string) {
  const lines = [
    '========================================',
    '            AAPKA PG - RECEIPT          ',
    '        (Demo payment simulation)       ',
    '========================================',
    `PG Name      : ${pgName}`,
    `Tenant       : ${tenantName}`,
    `Room         : ${roomNumber}`,
    '----------------------------------------',
    `Payment Type : ${payment.type}`,
    `Month        : ${monthLabel(payment.month)}`,
    `Amount       : Rs. ${payment.amount}`,
    `Method       : ${payment.method}`,
    `Status       : ${payment.status}`,
    `Reference    : ${payment.reference ?? '—'}`,
    `Paid On      : ${payment.paidAt ? formatDate(payment.paidAt) : '—'}`,
    '----------------------------------------',
    'This is a simulated receipt generated by',
    'the Aapka PG demo. No real transaction',
    'has been processed.',
    '========================================',
  ];
  const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `receipt-${payment.type.toLowerCase()}-${payment.month}.txt`;
  a.click();
  URL.revokeObjectURL(url);
}

export default function TenantRentPage() {
  const { data, payPayment } = useAppStore();
  const toast = useToast();
  const tenant = data.tenants.find((t) => t.id === data.activeTenantId);
  const [method, setMethod] = useState<PaymentMethod>('UPI');
  const [confirmOpen, setConfirmOpen] = useState(false);

  if (!tenant) {
    return (
      <AppLayout role="tenant" title="Rent & Payments">
        <div className="card p-10 text-center text-dark-500">Tenant profile not found. Please log in again.</div>
      </AppLayout>
    );
  }

  const month = currentMonth();
  const room = data.rooms.find((r) => r.id === tenant.roomId);
  const rentPayment = data.payments.find(
    (p) => p.tenantId === tenant.id && p.type === 'Rent' && p.month === month
  );
  const amount = rentPayment?.amount ?? tenant.monthlyRent + data.settings.foodCharge;
  const isPaid = rentPayment?.status === 'Paid';

  const paymentHistory = data.payments
    .filter((p) => p.tenantId === tenant.id)
    .sort((a, b) => (b.paidAt ?? b.dueDate).localeCompare(a.paidAt ?? a.dueDate))
    .slice(0, 10);

  const confirmPay = () => {
    if (!rentPayment) return;
    payPayment(rentPayment.id, method);
    setConfirmOpen(false);
    toast.show('Payment successful! Receipt is ready to download.', 'success');
  };

  return (
    <AppLayout role="tenant" title="Rent & Payments" subtitle={monthLabel(month)}>
      <div className="space-y-6">
        <div className="grid lg:grid-cols-3 gap-6">
          {/* Payment Summary */}
          <div className="lg:col-span-2 space-y-6">
            <div className="card p-6">
              <h2 className="text-xl font-bold text-dark-900 mb-6">Pay Monthly Rent</h2>

              <div className="bg-gradient-to-br from-primary to-secondary rounded-2xl p-6 text-white mb-6">
                <div className="flex items-center justify-between mb-2">
                  <span className="opacity-80">Amount Due — {monthLabel(month)}</span>
                  <PaymentStatusBadge status={rentPayment?.status ?? 'Pending'} />
                </div>
                <div className="text-4xl font-bold mb-4">{formatINR(amount)}</div>
                <div className="flex flex-wrap items-center gap-x-6 gap-y-1 text-sm opacity-90">
                  <span>Room {room?.roomNumber}, Bed {tenant.bedNumber}</span>
                  <span>Due {formatDate(rentPayment?.dueDate ?? `${month}-05`)}</span>
                </div>
              </div>

              <div className="grid grid-cols-2 sm:grid-cols-3 gap-4 mb-6">
                <div className="p-4 rounded-xl bg-background-200">
                  <div className="text-xs text-dark-400 mb-1">Monthly Rent</div>
                  <div className="font-semibold">{formatINR(tenant.monthlyRent)}</div>
                </div>
                <div className="p-4 rounded-xl bg-background-200">
                  <div className="text-xs text-dark-400 mb-1">Food Charges</div>
                  <div className="font-semibold">{formatINR(data.settings.foodCharge)}</div>
                </div>
                <div className="p-4 rounded-xl bg-background-200">
                  <div className="text-xs text-dark-400 mb-1">Security Deposit</div>
                  <div className="font-semibold text-success">{formatINR(tenant.securityDeposit)}</div>
                </div>
              </div>

              {isPaid ? (
                <div className="space-y-4">
                  <div className="bg-success-light text-success px-4 py-3 rounded-xl flex items-center gap-3">
                    <ShieldCheck size={20} />
                    <span className="font-medium">
                      Rent for {monthLabel(month)} is paid. Thank you!
                    </span>
                  </div>
                  <button
                    onClick={() => rentPayment && downloadReceipt(rentPayment, tenant.fullName, data.settings.name, room?.roomNumber ?? '-')}
                    className="w-full btn-secondary py-3"
                  >
                    <Download size={16} /> Download Receipt
                  </button>
                </div>
              ) : (
                <>
                  <div className="mb-4">
                    <label className="block text-sm font-medium text-dark-700 mb-3">Payment Method</label>
                    <div className="grid grid-cols-3 gap-3">
                      {([
                        { key: 'UPI', icon: Wallet, label: 'UPI' },
                        { key: 'Card', icon: CreditCard, label: 'Debit / Credit Card' },
                        { key: 'Net Banking', icon: Landmark, label: 'Net Banking' },
                      ] as const).map(({ key, icon: Icon, label }) => (
                        <button
                          key={key}
                          type="button"
                          onClick={() => setMethod(key)}
                          className={`flex flex-col items-center justify-center gap-1 py-3 px-2 rounded-xl border transition-all ${
                            method === key
                              ? 'border-primary bg-primary-50 text-primary font-medium'
                              : 'border-background-300 hover:border-primary text-dark-600'
                          }`}
                        >
                          <Icon size={18} />
                          <span className="text-xs text-center">{label}</span>
                        </button>
                      ))}
                    </div>
                  </div>

                  <button onClick={() => setConfirmOpen(true)} className="w-full btn-primary py-4 text-lg">
                    Pay {formatINR(amount)} Now
                  </button>

                  <div className="mt-3 flex items-start gap-2 text-xs text-dark-400">
                    <Info size={14} className="mt-0.5 shrink-0" />
                    <span>
                      Demo environment: this simulates a payment flow. No real money is transferred and no banking credentials are collected. UPI AutoPay can be enabled in production.
                    </span>
                  </div>
                </>
              )}
            </div>

            {/* Payment History */}
            <div className="card p-6">
              <h3 className="font-bold text-lg text-dark-900 mb-4">Payment History</h3>
              <div className="space-y-4">
                {paymentHistory.length > 0 ? (
                  paymentHistory.map((payment) => (
                    <div key={payment.id} className="flex items-center justify-between p-4 rounded-xl bg-background-200">
                      <div>
                        <div className="font-medium text-dark-900">
                          {monthLabel(payment.month)} <span className="text-xs text-dark-400 font-normal">• {payment.type}</span>
                        </div>
                        <div className="text-xs text-dark-400 mt-0.5">
                          {payment.status === 'Paid' ? (
                            <>
                              <span className="text-success">Paid</span> on {formatDate(payment.paidAt)} • {payment.method}
                            </>
                          ) : (
                            <span className={payment.status === 'Overdue' ? 'text-error' : 'text-warning'}>
                              {payment.status} • Due {formatDate(payment.dueDate)}
                            </span>
                          )}
                        </div>
                      </div>
                      <div className="text-right">
                        <div className="font-bold text-lg">{formatINR(payment.amount)}</div>
                        {payment.status === 'Paid' && (
                          <button
                            onClick={() => downloadReceipt(payment, tenant.fullName, data.settings.name, room?.roomNumber ?? '-')}
                            className="text-xs text-primary hover:underline inline-flex items-center gap-1 mt-1"
                          >
                            <Download size={12} /> Receipt
                          </button>
                        )}
                      </div>
                    </div>
                  ))
                ) : (
                  <div className="text-center py-8 text-dark-500">No payment history available</div>
                )}
              </div>
            </div>
          </div>

          {/* Tenant Info Sidebar */}
          <div className="space-y-6">
            <div className="card p-6">
              <h3 className="font-bold text-lg text-dark-900 mb-4">Your Details</h3>
              <div className="space-y-4">
                <div className="flex justify-between">
                  <span className="text-dark-400">Room No.</span>
                  <span className="font-medium">{room?.roomNumber ?? '—'}</span>
                </div>
                <div className="flex justify-between">
                  <span className="text-dark-400">Bed No.</span>
                  <span className="font-medium">{tenant.bedNumber}</span>
                </div>
                <div className="flex justify-between">
                  <span className="text-dark-400">Security Deposit</span>
                  <span className="font-medium text-success">{formatINR(tenant.securityDeposit)}</span>
                </div>
                <div className="flex justify-between">
                  <span className="text-dark-400">Mobile</span>
                  <span className="font-medium">{tenant.mobile}</span>
                </div>
                <div className="flex justify-between">
                  <span className="text-dark-400">Joining Date</span>
                  <span className="font-medium">{formatDate(tenant.joiningDate)}</span>
                </div>
              </div>
            </div>

            <div className="card p-6 bg-gradient-to-br from-primary to-secondary text-white">
              <h3 className="font-bold mb-2">Payment Reminders</h3>
              <p className="text-sm opacity-90 mb-3">
                You will get an automatic reminder in the app before the due date ({formatDate(rentPayment?.dueDate ?? `${month}-05`)}) if your rent is still pending.
              </p>
              <p className="text-xs opacity-70">
                In production this reminder is also delivered via WhatsApp.
              </p>
            </div>
          </div>
        </div>

        {/* Confirm payment modal */}
        <Modal
          open={confirmOpen}
          onClose={() => setConfirmOpen(false)}
          title="Confirm Payment"
          size="sm"
          footer={
            <>
              <button className="btn-secondary" onClick={() => setConfirmOpen(false)}>Cancel</button>
              <button className="btn-primary" onClick={confirmPay}>Pay {formatINR(amount)}</button>
            </>
          }
        >
          <div className="space-y-3 text-sm">
            <div className="flex justify-between"><span className="text-dark-500">PG</span><span className="font-medium">{data.settings.name}</span></div>
            <div className="flex justify-between"><span className="text-dark-500">Paying for</span><span className="font-medium">Rent — {monthLabel(month)}</span></div>
            <div className="flex justify-between"><span className="text-dark-500">Method</span><span className="font-medium">{method}</span></div>
            <div className="flex justify-between text-base"><span className="text-dark-500">Amount</span><span className="font-bold">{formatINR(amount)}</span></div>
            <div className="mt-2 p-3 rounded-xl bg-warning-light text-warning text-xs flex items-start gap-2">
              <Info size={14} className="mt-0.5 shrink-0" />
              <span>This is a <strong>demo payment simulation</strong> — no real bank transaction will occur.</span>
            </div>
          </div>
        </Modal>
      </div>
    </AppLayout>
  );
}
