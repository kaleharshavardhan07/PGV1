// Subscription policy helpers: feature matrix, plan limits, invoice generation.
// SaaS subscription billing is kept completely separate from tenant payment ledgers.

import type { PlanId, Subscription, SubscriptionInvoice, SubscriptionStatus } from '../types';
import { getPlan } from '../data/plans';

export type PlanFeature =
  | 'core' // rooms/beds, tenants, rent tracking, electricity, basic complaints (all plans)
  | 'autoReminders' // automated rent/electricity reminders (Growth+)
  | 'whatsapp' // WhatsApp channel (Growth+)
  | 'financialReports' // Growth+
  | 'vacantSharing' // Growth+
  | 'advancedComplaints' // Growth+
  | 'multiBranch' // Pro
  | 'advancedAnalytics' // Pro
  | 'autoWorkflows' // Pro
  | 'prioritySupport'; // Pro

const PLAN_FEATURES: Record<PlanId, PlanFeature[]> = {
  starter: ['core'],
  growth: ['core', 'autoReminders', 'whatsapp', 'financialReports', 'vacantSharing', 'advancedComplaints'],
  pro: [
    'core',
    'autoReminders',
    'whatsapp',
    'financialReports',
    'vacantSharing',
    'advancedComplaints',
    'multiBranch',
    'advancedAnalytics',
    'autoWorkflows',
    'prioritySupport',
  ],
};

/** Statuses that grant full access to the current plan's features. */
export const FULL_ACCESS_STATUSES: SubscriptionStatus[] = ['Trial', 'Active', 'Cancelled'];

/**
 * Whether the current subscription allows a feature.
 * Expired/suspended subscriptions keep essential access (view records, billing
 * history, manual entry, renew) but lose paid automation features.
 */
export const subscriptionAllows = (sub: Subscription, feature: PlanFeature): boolean => {
  if (feature === 'core') return true;
  if (!FULL_ACCESS_STATUSES.includes(sub.status)) return false;
  return PLAN_FEATURES[sub.planId].includes(feature);
};

/** Channels available for the plan (in-app is always available). */
export const planAllowsChannel = (sub: Subscription, channel: 'WhatsApp' | 'SMS' | 'Email'): boolean => {
  if (!FULL_ACCESS_STATUSES.includes(sub.status)) return false;
  if (channel === 'WhatsApp') return subscriptionAllows(sub, 'whatsapp');
  return true; // SMS and Email are available on all plans
};

export const planAllowsChannelForPlan = (planId: PlanId, channel: 'WhatsApp' | 'SMS' | 'Email'): boolean => {
  if (channel === 'WhatsApp') return PLAN_FEATURES[planId].includes('whatsapp');
  return true;
};

export const limitLabel = (limit: number | null): string => (limit === null ? 'Unlimited' : String(limit));

export const usageSummary = (
  sub: Subscription,
  usage: { rooms: number; beds: number; branches: number }
) => {
  const plan = getPlan(sub.planId);
  return [
    { label: 'Rooms', used: usage.rooms, limit: plan.limits.rooms },
    { label: 'Beds', used: usage.beds, limit: plan.limits.beds },
    { label: 'PG Branches', used: usage.branches, limit: plan.limits.branches },
  ];
};

export const isOverLimit = (used: number, limit: number | null) => limit !== null && used >= limit;

export const nextInvoiceNumber = (invoices: SubscriptionInvoice[]): string => {
  const n = invoices.length + 1;
  return `APG-${new Date().getFullYear()}-${String(n).padStart(4, '0')}`;
};

/** Build a downloadable HTML invoice and trigger the browser download. */
export const downloadInvoice = (invoice: SubscriptionInvoice, pgName: string, ownerName: string) => {
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>Invoice ${invoice.number}</title>
<style>
  body{font-family:Arial,Helvetica,sans-serif;max-width:720px;margin:40px auto;color:#17132B}
  h1{color:#6938EF}
  table{width:100%;border-collapse:collapse;margin-top:24px}
  td,th{border:1px solid #ddd;padding:10px;text-align:left}
  .total{font-weight:bold;font-size:18px}
  .muted{color:#777;font-size:12px}
</style></head><body>
<h1>Aapka PG – Subscription Invoice</h1>
<p class="muted">This is a demo invoice generated by the prototype. No real payment was processed.</p>
<table>
  <tr><th>Invoice Number</th><td>${invoice.number}</td></tr>
  <tr><th>Billed To</th><td>${pgName} (${ownerName})</td></tr>
  <tr><th>Date</th><td>${new Date(invoice.date).toLocaleDateString('en-IN')}</td></tr>
  <tr><th>Plan</th><td>${invoice.planId.toUpperCase()} (${invoice.cycle})</td></tr>
  <tr><th>Payment Method</th><td>${invoice.method} (simulated)</td></tr>
  <tr><th>Status</th><td>${invoice.status}</td></tr>
  <tr><th class="total">Amount</th><td class="total">₹${invoice.amount.toLocaleString('en-IN')}</td></tr>
</table>
<p class="muted">Aapka PG · PWS Coding · pwscoding.co.in · pwscoding@gmail.com</p>
</body></html>`;
  const blob = new Blob([html], { type: 'text/html' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${invoice.number}.html`;
  a.click();
  URL.revokeObjectURL(url);
};
